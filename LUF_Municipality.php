        if(!$this->Visible) return;

        $GridBlock = "Grid " . $this->ComponentName;
        $ParentPath = $Tpl->block_path;
        $Tpl->block_path = $ParentPath . "/" . $GridBlock;


        if (!$this->IsEmpty) {
            $this->ControlsVisible["Municipality"] = $this->Municipality->Visible;
            while ($this->ForceIteration || (($this->RowNumber < $this->PageSize) &&  ($this->HasRecord = $this->DataSource->has_next_record()))) {
                $this->RowNumber++;
                if ($this->HasRecord) {
                    $this->DataSource->next_record();
                    $this->DataSource->SetValues();
                }
                $Tpl->block_path = $ParentPath . "/" . $GridBlock . "/Row";
                $this->Municipality->SetValue($this->DataSource->Municipality->GetValue());
                $this->Municipality->Parameters = CCGetQueryString("QueryString", array("ccsForm"));
                $this->Municipality->Parameters = CCAddParam($this->Municipality->Parameters, "MunicipalityID", $this->DataSource->f("MunicipalityID"));
